# Generates src/<page>-page/mount.js from each embed.html (the markup stays editable as HTML).
import json, re, os
root = os.path.join(os.path.dirname(__file__), '..')
T = """/* Montel · %(page)s page mount (generated by build/gen-mounts.py from embed.html, do not edit)
   Swaps the static hero image for the animation. Assets load from the same repo commit as this bundle. */
(function () {
  'use strict';
  var box = document.querySelector('.page_hero__img_container');
  if (!box || box.querySelector('[%(attr)s]')) return;
  var s = document.currentScript && document.currentScript.src || '';
  var base = s ? s.replace(/dist\\/[^\\/]*$/, '') + 'assets/%(page)s/' : 'assets/';
  document.documentElement.classList.add('mtl-js');
  var wrap = document.createElement('div');
  wrap.className = 'mtl-hero-mount';
  wrap.innerHTML = %(html)s.replace(/@ASSETS@/g, base);
  var img = box.querySelector('img');
  var w = img && (+img.getAttribute('width') || img.naturalWidth), h = img && (+img.getAttribute('height') || img.naturalHeight);
  if (!(w && h) && img) { var r = img.getBoundingClientRect(); w = r.width; h = r.height; }
  if (w && h) wrap.style.setProperty('--mtl-hero-ar', w + ' / ' + h);
  box.classList.add('has-mtl-hero');
  box.appendChild(wrap);
})();
"""
for page, attr in [('analytics', 'data-mtl-fa'), ('risk', 'data-mtl-risk'), ('news', 'data-mtl-news')]:
    d = os.path.join(root, 'src', page + '-page')
    html = open(os.path.join(d, 'embed.html')).read()
    html = re.sub(r'<!--.*?-->', '', html, flags=re.S)
    html = re.sub(r'>\s+<', '><', html).strip()
    html = html.replace('"assets/', '"@ASSETS@')
    open(os.path.join(d, 'mount.js'), 'w').write(T % {'page': page, 'attr': attr, 'html': json.dumps(html)})
    print(page, len(html))
