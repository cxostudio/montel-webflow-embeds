# Generates src/<page>-page/mount.js from each embed.html (the markup stays editable as HTML).
import json, re, os
root = os.path.join(os.path.dirname(__file__), '..')
T = """/* Montel · %(page)s page mount (generated by build/gen-mounts.py from embed.html, do not edit)
   Swaps the static hero image for the animation. Assets load from the same repo commit as this bundle. */
(function () {
  'use strict';
  var box = document.querySelector('.page_hero__img_container');
  if (!box || box.querySelector('[%(attr)s]')) return;
  var s = document.currentScript && document.currentScript.src || '';
  var base = s ? s.replace(/dist\\/[^\\/]*$/, '') + 'assets/%(page)s/' : 'assets/';
  document.documentElement.classList.add('mtl-js');
  var wrap = document.createElement('div');
  wrap.className = 'mtl-hero-mount';
  wrap.innerHTML = %(html)s.replace(/@ASSETS@/g, base);
  var img = box.querySelector('img');
  var w = img && (+img.getAttribute('width') || img.naturalWidth), h = img && (+img.getAttribute('height') || img.naturalHeight);
  if (!(w && h) && img) { var r = img.getBoundingClientRect(); w = r.width; h = r.height; }
  if (w && h) wrap.style.setProperty('--mtl-hero-ar', w + ' / ' + h);
  box.classList.add('has-mtl-hero');
  box.appendChild(wrap);
})();
"""
for page, attr in [('analytics', 'data-mtl-fa'), ('risk', 'data-mtl-risk'), ('news', 'data-mtl-news')]:
    d = os.path.join(root, 'src', page + '-page')
    html = open(os.path.join(d, 'embed.html')).read()
    html = re.sub(r'<!--.*?-->', '', html, flags=re.S)
    html = re.sub(r'>\s+<', '><', html).strip()
    html = html.replace('"assets/', '"@ASSETS@')
    open(os.path.join(d, 'mount.js'), 'w').write(T % {'page': page, 'attr': attr, 'html': json.dumps(html)})
    print(page, len(html))

# Home: five slides, one per hero tab. The tab script keeps toggling the images;
# each slide follows its image's "active" class, so the tab buttons, arrows and progress bars work unchanged.
H = """/* Montel · Home page mount (generated by build/gen-mounts.py from embed-*.html, do not edit) */
(function () {
  'use strict';
  var box = document.querySelector('.hero__tab_content');
  if (!box || box.querySelector('[data-mtl-slide]')) return;
  var s = document.currentScript && document.currentScript.src || '';
  var base = s ? s.replace(/dist\\/[^\\/]*$/, '') + 'assets/home/' : 'assets/';
  var html = %(slides)s;
  var imgs = [].slice.call(box.querySelectorAll(':scope > img'));
  if (imgs.length !== html.length) return;
  document.documentElement.classList.add('mtl-js');
  var wraps = imgs.map(function (img, i) {
    var w = document.createElement('div');
    w.className = 'mtl-tab-slide';
    /* only the first slide's photos load up front; the rest wait (hidden + lazy) and are warmed after page load */
    w.innerHTML = html[i].replace(/@ASSETS@/g, base).replace(/loading="eager"/g, i ? 'loading="lazy"' : 'loading="eager" fetchpriority="high"');
    box.appendChild(w);
    return w;
  });
  /* before the tab script has marked a tab active, show the first slide (no blank frame) */
  function sync() { var any = imgs.some(function (img) { return img.classList.contains('active'); }); imgs.forEach(function (img, i) { var on = any ? img.classList.contains('active') : i === 0; wraps[i].style.display = on ? 'block' : 'none'; wraps[i].classList.toggle('active', on); }); }
  /* phones crop each slide to its main card: flag the layers that sit mostly outside the crop so CSS can drop them */
  wraps.forEach(function (w) {
    var r = w.querySelector('[data-mtl-crop]'); if (!r) return;
    var c = r.getAttribute('data-mtl-crop').split(',').map(Number);
    [].slice.call(r.querySelectorAll('.mtl-layer')).forEach(function (l) {
      var x = parseFloat(l.style.left), y = parseFloat(l.style.top), lw = parseFloat(l.style.width), lh = parseFloat(l.style.height);
      var ix = Math.max(0, Math.min(x + lw, c[0] + c[2]) - Math.max(x, c[0])), iy = Math.max(0, Math.min(y + lh, c[1] + c[3]) - Math.max(y, c[1]));
      if (ix * iy < .8 * lw * lh) l.classList.add('mtl-off');
    });
  });
  box.classList.add('has-mtl-slides');
  sync();
  var mo = new MutationObserver(sync);
  imgs.forEach(function (img) { mo.observe(img, { attributes: true, attributeFilter: ['class'] }); });
  function warm() { setTimeout(function () { [].slice.call(box.querySelectorAll('.mtl-tab-slide img[loading="lazy"]')).forEach(function (im) { im.loading = 'eager'; }); }, 1200); }
  if (document.readyState === 'complete') warm(); else window.addEventListener('load', warm);
})();
"""
d = os.path.join(root, 'src', 'home-page'); out = []
for s in ['trade', 'forecast', 'assets', 'ppa', 'advice']:
    t = open(os.path.join(d, 'embed-%s.html' % s)).read()
    t = re.sub(r'<!--.*?-->', '', t, flags=re.S); t = re.sub(r'>\s+<', '><', t).strip()
    out.append(t.replace('"assets/', '"@ASSETS@'))
open(os.path.join(d, 'mount.js'), 'w').write(H % {'slides': json.dumps(out)})
print('home', sum(map(len, out)))
